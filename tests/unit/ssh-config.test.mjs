test('renderHostBlock renders every supported directive and omits undefined ones', () => {
	const text = renderHostBlock({
		alias: 'prod',
		hostname: '10.0.0.5',
		user: 'ubuntu',
		port: 2222,
		identityFile: '~/.ssh/id_ed25519',
		proxyJump: 'bastion',
		proxyCommand: 'nc %h %p',
		identitiesOnly: true,
		forwardAgent: false,
		serverAliveInterval: 30,
		serverAliveCountMax: 3,
		strictHostKeyChecking: 'yes',
		userKnownHostsFile: '/tmp/known_hosts',
		connectionAttempts: 2,
		connectTimeout: 10,
		extraOptions: [{ key: 'Compression', value: 'yes' }],
		remoteWorkspace: '/srv/app',
	});
	assert.match(text, /^Host prod$/m);
	assert.match(text, /^ {2}HostName 10\.0\.0\.5$/m);
	assert.match(text, /^ {2}IdentitiesOnly yes$/m);
	assert.match(text, /^ {2}ForwardAgent no$/m);
	assert.match(text, /^ {2}StrictHostKeyChecking yes$/m);
	assert.match(text, /^ {2}Compression yes$/m);
	assert.match(text, /^ {2}ProxyCommand nc %h %p$/m);
	assert.doesNotMatch(text, /ProxyCommand "/);
	assert.doesNotMatch(text, /RemoteWorkspace|remoteWorkspace/);
	const minimal = renderHostBlock({ alias: 'bare', hostname: 'example.com' });
	assert.equal(minimal.trimEnd(), 'Host bare\n  HostName example.com\n  StrictHostKeyChecking yes');
});

test('command-valued directives are emitted without config-level quotes', () => {
	const text = renderHostBlock({
		alias: 'proxy',
		hostname: 'example.com',
		proxyCommand: 'nc -X 5 -x 127.0.0.1:7897 %h %p',
		extraOptions: [
			{ key: 'LocalCommand', value: 'echo "ready"' },
			{ key: 'Compression', value: 'yes' },
		],
	});
	assert.match(text, /^ {2}ProxyCommand nc -X 5 -x 127\.0\.0\.1:7897 %h %p$/m);
	assert.match(text, /^ {2}LocalCommand echo "ready"$/m);
	assert.match(text, /^ {2}Compression yes$/m);
});

test('renderManagedConfig starts with the warning header and separates hosts', () => {
	const text = renderManagedConfig([
		{ alias: 'a', hostname: 'h1' },
		{ alias: 'b', hostname: 'h2' },
	]);
	assert.match(text, /^# Generated by @junjiangao\/dsh-plugin-remote-ssh/m);
	assert.match(text, /Host a\n {2}HostName h1\n {2}StrictHostKeyChecking yes\n\nHost b\n {2}HostName h2/);
});

test('writeManagedConfig writes a private file', async () => {
	const dir = await mkdtemp(join(tmpdir(), 'rssh-cfg-'));
	const file = join(dir, 'ssh_config');
	await writeManagedConfig(file, [{ alias: 'a', hostname: 'h' }]);
	const mode = (await stat(file)).mode & 0o777;
	assert.equal(mode, 0o600);
	assert.match(await readFile(file, 'utf8'), /Host a/);
});

test('ensureManagedInclude inserts at the top and is idempotent', async () => {
	const dir = await mkdtemp(join(tmpdir(), 'rssh-cfg-'));
	const config = join(dir, 'config');
	const fragment = join(dir, 'ssh_config');
	await writeFile(config, 'Host existing\n  HostName example.com\n');
	await writeManagedConfig(fragment, []);
	const first = await ensureManagedInclude(config, fragment);
	assert.equal(first.changed, true);
	const text = await readFile(config, 'utf8');
	assert.match(text, new RegExp(`^${INCLUDE_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`));
	assert.match(text, /Host existing/);
	const second = await ensureManagedInclude(config, fragment);
	assert.equal(second.changed, false);
	assert.equal(await readFile(config, 'utf8'), text);
});

test('ensureManagedInclude creates a missing config and its directory', async () => {
	const dir = await mkdtemp(join(tmpdir(), 'rssh-cfg-'));
	const config = join(dir, 'nested', '.ssh', 'config');
	const fragment = join(dir, 'ssh_config');
	await mkdir(join(dir, 'nested'), { recursive: true });
	const result = await ensureManagedInclude(config, fragment);
	assert.equal(result.created, true);
	assert.match(await readFile(config, 'utf8'), /Include /);
});

test('parseUserConfig walks includes, skips wildcards and keeps literal aliases', async () => {
	const dir = await mkdtemp(join(tmpdir(), 'rssh-cfg-'));
	const nested = join(dir, 'extra.conf');
	const config = join(dir, 'config');
	await writeFile(config, [
		'Include ~/.ssh/extra-*.conf',
		`Include ${nested}`,
		'Host alpha beta',
		'  User root',
		'',
		'Host *.internal',
		'  User nobody',
		'',
		'Host gamma',
		'  HostName 10.0.0.3',
	].join('\n'));
	await writeFile(nested, 'Host nested\n  HostName nested.example.com\n');
	const parsed = await parseUserConfig(config);
	const aliases = parsed.aliases.map((entry) => entry.alias).sort();
	assert.deepEqual(aliases, ['alpha', 'beta', 'gamma', 'nested']);
	assert.equal(parsed.aliases.find((entry) => entry.alias === 'nested').file, nested);
});

test('parseSshG normalizes values and the strict mode', () => {
	const facts = parseSshG([
		'host unit',
		'hostname 10.0.0.9',
		'user root',
		'port 2222',
		'identityfile ~/.ssh/id_ed25519',
		'proxyjump bastion',
		'proxycommand nc %h %p',
		'stricthostkeychecking true',
	].join('\n'));
	assert.equal(facts.alias, 'unit');
	assert.equal(facts.hostname, '10.0.0.9');
	assert.equal(facts.user, 'root');
	assert.equal(facts.port, 2222);
	assert.equal(facts.strictHostKeyChecking, 'yes');
	assert.equal(parseSshG('stricthostkeychecking false').strictHostKeyChecking, 'no');
	assert.equal(parseSshG('stricthostkeychecking ask').strictHostKeyChecking, undefined);
});

test('resolveAlias resolves a host through OpenSSH without connecting', async () => {
	const dir = await mkdtemp(join(tmpdir(), 'rssh-cfg-'));
	const configPath = join(dir, 'config');
	await writeFile(configPath, 'Host unit-test\n  HostName 127.0.0.1\n  User tester\n  Port 2222\n  IdentityFile ~/.ssh/id_ed25519\n');
	const config = resolveConfig({ sshConfigPath: configPath });
	const facts = await resolveAlias(config, 'unit-test');
	assert.equal(facts.hostname, '127.0.0.1');
	assert.equal(facts.user, 'tester');
	assert.equal(facts.port, 2222);
});
