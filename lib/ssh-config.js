/**
 * OpenSSH user-config integration.
 *
 * Two responsibilities:
 *  1. Derive `~/.dsh/remote-ssh/ssh_config` from the managed host list.
 *  2. Keep a small, idempotent `Include` block at the top of `~/.ssh/config`,
 *     preserving every byte outside that block and validating the result with
 *     `ssh -G` before accepting it.
 *
 * Read-only discovery of the user's own aliases is best-effort: a malformed
 * entry must never hide the rest of the list.
 * @module @junjiangao/dsh-plugin-remote-ssh/ssh-config
 */
import { chmod, copyFile, lstat, mkdir, readFile, readdir, realpath, rename, stat, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join } from 'node:path';
import { homedir } from 'node:os';
import { runProcess } from './ssh.js';
import { RemoteSshError, ERROR_CODES } from './errors.js';
import { resolveSshConfigPath } from './paths.js';

/** First line of the managed block in `~/.ssh/config`. */
export const INCLUDE_BEGIN = '# BEGIN dsh-plugin-remote-ssh (managed; do not edit)';
/** Last line of the managed block in `~/.ssh/config`. */
export const INCLUDE_END = '# END dsh-plugin-remote-ssh';
/** Header of the generated ssh_config fragment. */
export const MANAGED_CONFIG_HEADER = '# Generated by @junjiangao/dsh-plugin-remote-ssh. Do not edit; use the Web panel.';
/** Maximum Include recursion depth. */
const MAX_INCLUDE_DEPTH = 16;

/** Format one ordinary ssh_config value, quoting whitespace and comment characters. */
export function formatConfigValue(value) {
	const text = String(value);
	if (text === '') return '""';
	if (/[\s#"'\\]/.test(text)) return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
	return text;
}

/**
 * Directives whose value is a command line handed to the shell.
 *
 * OpenSSH passes these values through verbatim (the shell tokenizes them), so
 * wrapping the whole value in config-level quotes makes the shell look for an
 * executable whose name contains spaces. Emit them raw instead.
 */
const COMMAND_VALUE_DIRECTIVES = new Set(['proxycommand', 'localcommand', 'remotecommand', 'knownhostscommand']);

/** Render one Host block from a persisted host record. */
export function renderHostBlock(host) {
	const lines = [`Host ${host.alias}`];
	const addRaw = (key, value) => {
		if (value !== undefined && value !== null && value !== '') lines.push(`  ${key} ${String(value)}`);
	};
	const add = (key, value) => {
		if (value !== undefined && value !== null && value !== '') {
			if (COMMAND_VALUE_DIRECTIVES.has(String(key).toLowerCase())) addRaw(key, value);
			else lines.push(`  ${key} ${formatConfigValue(value)}`);
		}
	};
	add('HostName', host.hostname);
	add('User', host.user);
	add('Port', host.port);
	add('IdentityFile', host.identityFile);
	add('ProxyJump', host.proxyJump);
	add('ProxyCommand', host.proxyCommand);
	if (host.identitiesOnly === true) lines.push('  IdentitiesOnly yes');
	if (host.forwardAgent === true) lines.push('  ForwardAgent yes');
	else if (host.forwardAgent === false) lines.push('  ForwardAgent no');
	add('ServerAliveInterval', host.serverAliveInterval);
	add('ServerAliveCountMax', host.serverAliveCountMax);
	add('StrictHostKeyChecking', host.strictHostKeyChecking ?? 'yes');
	add('UserKnownHostsFile', host.userKnownHostsFile);
	add('ConnectionAttempts', host.connectionAttempts);
	add('ConnectTimeout', host.connectTimeout);
	for (const option of host.extraOptions ?? []) add(option.key, option.value);
	return `${lines.join('\n')}\n`;
}

/** Render the complete managed ssh_config fragment. */
export function renderManagedConfig(hosts) {
	const parts = [`${MANAGED_CONFIG_HEADER}\n`];
	for (const host of hosts) parts.push(`\n${renderHostBlock(host)}`);
	return parts.join('');
}

/**
 * Write the generated ssh_config fragment atomically.
 * @param file - absolute path to `~/.dsh/remote-ssh/ssh_config`.
 * @param hosts - persisted host records.
 */
export async function writeManagedConfig(file, hosts) {
	await atomicWrite(file, renderManagedConfig(hosts), 0o600);
}

/** Build the exact Include block for one generated config path. */
export function renderIncludeBlock(managedConfigFile) {
	return `${INCLUDE_BEGIN}\nInclude ${formatConfigValue(managedConfigFile)}\n${INCLUDE_END}\n`;
}

/** Locate the managed block, if present. */
function locateBlock(content) {
	const begin = content.indexOf(INCLUDE_BEGIN);
	const end = content.indexOf(INCLUDE_END);
	if (begin === -1 && end === -1) return undefined;
	if (begin === -1 || end === -1 || end < begin) {
		throw new RemoteSshError(
			ERROR_CODES.conflict,
			'the managed Include block in ~/.ssh/config is incomplete',
			{ hint: `Remove the lines between "${INCLUDE_BEGIN}" and "${INCLUDE_END}" and retry.` },
		);
	}
	const endOfEnd = content.indexOf('\n', end);
	return { start: begin, end: endOfEnd === -1 ? content.length : endOfEnd + 1 };
}

/**
 * Ensure `~/.ssh/config` includes the generated fragment.
 *
 * The block is placed at the very top so absolute Host values win over the
 * user's later `Host *` defaults, matching the plan's shadowing contract.
 * @returns `{ changed, backupPath, created }`.
 */
export async function ensureManagedInclude(sshConfigPath, managedConfigFile) {
	const target = await resolveWriteTarget(sshConfigPath);
	await mkdir(dirname(target), { recursive: true, mode: 0o700 });
	let content = '';
	let existed = true;
	try {
		content = await readFile(target, 'utf8');
	} catch (error) {
		if (error?.code !== 'ENOENT') throw error;
		existed = false;
	}
	const block = renderIncludeBlock(managedConfigFile);
	const located = locateBlock(content);
	let next;
	if (located === undefined) {
		const suffix = content === '' ? '' : content.startsWith('\n') ? content : `\n${content}`;
		next = `${block}${suffix}`;
	} else {
		next = `${content.slice(0, located.start)}${block}${content.slice(located.end)}`;
	}
	if (next === content) return { changed: false, backupPath: undefined, created: !existed };
	let backupPath;
	if (existed) {
		const candidate = `${target}.dsh-remote-ssh.bak`;
		try {
			await lstat(candidate);
		} catch {
			await copyFile(target, candidate);
			await chmod(candidate, 0o600).catch(() => undefined);
			backupPath = candidate;
		}
	}
	await atomicWrite(target, next, existed ? (await stat(target)).mode & 0o777 : 0o600);
	return { changed: true, backupPath, created: !existed };
}

/** Remove the managed Include block from `~/.ssh/config` (used by tests/tools). */
export async function removeManagedInclude(sshConfigPath) {
	const target = await resolveWriteTarget(sshConfigPath);
	let content;
	try {
		content = await readFile(target, 'utf8');
	} catch (error) {
		if (error?.code === 'ENOENT') return false;
		throw error;
	}
	const located = locateBlock(content);
	if (located === undefined) return false;
	await atomicWrite(target, content.slice(0, located.start) + content.slice(located.end), (await stat(target)).mode & 0o777);
	return true;
}

/** Resolve a symlinked config to the file the write should actually replace. */
async function resolveWriteTarget(file) {
	try {
		return await realpath(file);
	} catch (error) {
		if (error?.code === 'ENOENT') return file;
		throw error;
	}
}

/** Write one file through a same-directory temporary and rename. */
async function atomicWrite(file, content, mode) {
	await mkdir(dirname(file), { recursive: true, mode: 0o700 });
	const temporary = `${file}.tmp-${process.pid}-${Date.now()}`;
	await writeFile(temporary, content, { encoding: 'utf8', mode });
	await chmod(temporary, mode).catch(() => undefined);
	await rename(temporary, file);
}

/** Split one config line into whitespace-separated arguments, honoring quotes. */
export function splitConfigArgs(text) {
	const args = [];
	let current = '';
	let quote = '';
	let escaped = false;
	for (const character of text) {
		if (escaped) {
			current += character;
			escaped = false;
			continue;
		}
		if (character === '\\') {
			escaped = true;
			continue;
		}
		if (quote !== '') {
			if (character === quote) quote = '';
			else current += character;
			continue;
		}
		if (character === '"' || character === "'") {
			quote = character;
			continue;
		}
		if (character === ' ' || character === '\t') {
			if (current !== '') {
				args.push(current);
				current = '';
			}
			continue;
		}
		current += character;
	}
	if (current !== '') args.push(current);
	return args;
}

/** Strip one inline comment, honoring quotes. */
export function stripComment(line) {
	let quote = '';
	let escaped = false;
	for (let index = 0; index < line.length; index += 1) {
		const character = line[index];
		if (escaped) {
			escaped = false;
			continue;
		}
		if (character === '\\') {
			escaped = true;
			continue;
		}
		if (quote !== '') {
			if (character === quote) quote = '';
			continue;
		}
		if (character === '"' || character === "'") {
			quote = character;
			continue;
		}
		if (character === '#') return line.slice(0, index);
	}
	return line;
}

/** Expand `~` for a config path token. */
function expandConfigPath(value) {
	if (value === '~') return homedir();
	if (value.startsWith('~/')) return join(homedir(), value.slice(2));
	return value;
}

/** Expand one Include pattern to existing files (single directory level, glob(3)-like). */
async function expandInclude(pattern, configDir) {
	const expanded = expandConfigPath(pattern);
	const base = isAbsolute(expanded) ? expanded : join(configDir, expanded);
	if (!/[*?[]/.test(base)) return [base];
	const directory = dirname(base);
	const name = base.slice(directory.length + 1);
	const regex = new RegExp(
		`^${name
			.replace(/[.+^${}()|\\]/g, '\\$&')
			.replace(/\*/g, '[^/]*')
			.replace(/\?/g, '[^/]')
			.replace(/\[([^\]]*)\]/g, '[$1]')}$`,
	);
	let entries;
	try {
		entries = await readdir(directory);
	} catch {
		return [];
	}
	return entries.filter((entry) => regex.test(entry)).map((entry) => join(directory, entry)).sort();
}

/** One literal Host entry discovered in a user config. */
export function isLiteralHostPattern(pattern) {
	return pattern !== '' && !/[*?[\]]/.test(pattern) && !pattern.startsWith('!');
}

/**
 * Parse a user ssh config recursively.
 * @param sshConfigPath - absolute path.
 * @returns `{ aliases, includes, errors }`, aliases in first-seen order.
 */
export async function parseUserConfig(sshConfigPath) {
	const rootFile = expandConfigPath(sshConfigPath);
	const aliases = new Map();
	const errors = [];
	const visited = new Set();
	await walk(rootFile, 0);
	return { aliases: [...aliases.values()], errors };

	async function walk(file, depth) {
		if (depth > MAX_INCLUDE_DEPTH) {
			errors.push(`Include depth exceeded at ${file}`);
			return;
		}
		let real;
		try {
			real = await realpath(file);
		} catch (error) {
			if (error?.code !== 'ENOENT') errors.push(`${file}: ${error.message}`);
			return;
		}
		if (visited.has(real)) return;
		visited.add(real);
		let content;
		try {
			content = await readFile(real, 'utf8');
		} catch (error) {
			errors.push(`${file}: ${error.message}`);
			return;
		}
		const lines = content.split(/\r?\n/);
		for (let index = 0; index < lines.length; index += 1) {
			const line = stripComment(lines[index]).trim();
			if (line === '') continue;
			const args = splitConfigArgs(line);
			if (args.length === 0) continue;
			const keyword = args[0].toLowerCase();
			if (keyword === 'host') {
				for (const pattern of args.slice(1)) {
					if (!isLiteralHostPattern(pattern)) continue;
					if (!aliases.has(pattern)) {
						aliases.set(pattern, { alias: pattern, file: real, line: index + 1 });
					}
				}
			} else if (keyword === 'include') {
				for (const pattern of args.slice(1)) {
					const files = await expandInclude(pattern, dirname(real));
					for (const included of files) await walk(included, depth + 1);
				}
			}
		}
	}
}

/** Parsed connection facts for one alias, from `ssh -G`. */
export function parseSshG(text) {
	const values = new Map();
	for (const rawLine of text.split(/\r?\n/)) {
		const line = rawLine.trim();
		if (line === '') continue;
		const index = line.indexOf(' ');
		const key = (index === -1 ? line : line.slice(0, index)).toLowerCase();
		const value = index === -1 ? '' : line.slice(index + 1);
		if (!values.has(key)) values.set(key, value);
		else if (key === 'identityfile') values.set(key, `${values.get(key)}\n${value}`);
	}
	const first = (key) => values.get(key);
	const identity = first('identityfile');
	return {
		alias: first('host'),
		hostname: first('hostname'),
		user: first('user'),
		port: first('port') === undefined ? undefined : Number(first('port')),
		identityFile: identity === undefined ? undefined : identity.split('\n').filter(Boolean)[0],
		proxyJump: first('proxyjump'),
		proxyCommand: first('proxycommand'),
		identitiesOnly: first('identitiesonly') === 'yes',
		forwardAgent: first('forwardagent') === 'yes',
		serverAliveInterval: numberOrUndefined(first('serveraliveinterval')),
		serverAliveCountMax: numberOrUndefined(first('serveralivecountmax')),
		strictHostKeyChecking: normalizeStrict(first('stricthostkeychecking')),
		userKnownHostsFile: first('userknownhostsfile'),
		connectionAttempts: numberOrUndefined(first('connectionattempts')),
		connectTimeout: numberOrUndefined(first('connecttimeout')),
	};
}

/** Normalize OpenSSH's internal boolean spelling to the managed vocabulary. */
function normalizeStrict(value) {
	if (value === 'true' || value === 'yes') return 'yes';
	if (value === 'false' || value === 'no') return 'no';
	if (value === 'accept-new') return 'accept-new';
	return undefined;
}

/** Parse a numeric ssh -G value. */
function numberOrUndefined(value) {
	if (value === undefined) return undefined;
	const number = Number(value);
	return Number.isFinite(number) ? number : undefined;
}

/**
 * Resolve one alias exactly as OpenSSH would, without connecting.
 * @returns parsed connection facts.
 */
export async function resolveAlias(config, alias, options = {}) {
	const args = ['-F', options.sshConfigPath ?? resolveSshConfigPath(config), '-G', alias];
	const result = await runProcess(options.sshExecutable ?? config.sshExecutable, args, {
		timeoutMs: options.timeoutMs ?? 10_000,
		signal: options.signal,
	});
	if (result.code !== 0 || result.timedOut || result.aborted) {
		throw new RemoteSshError(
			ERROR_CODES.sshFailed,
			`ssh -G ${alias} failed: ${result.stderr.trim() || `exit ${String(result.code)}`}`,
		);
	}
	const facts = parseSshG(result.stdout);
	if (facts.alias === undefined) {
		throw new RemoteSshError(ERROR_CODES.sshFailed, `ssh -G ${alias} returned no host block`);
	}
	return facts;
}

/**
 * Validate every managed alias against the generated fragment.
 * @returns an array of human-readable mismatches; empty means valid.
 */
export async function verifyManagedHosts(config, hosts, options = {}) {
	const errors = [];
	for (const host of hosts) {
		try {
			const facts = await resolveAlias(config, host.alias, {
				sshConfigPath: options.sshConfigPath ?? config.sshConfigPath,
				sshExecutable: options.sshExecutable ?? config.sshExecutable,
				timeoutMs: options.timeoutMs,
				signal: options.signal,
			});
			if (facts.hostname !== undefined && host.hostname !== undefined
				&& facts.hostname.toLowerCase() !== host.hostname.toLowerCase()) {
				errors.push(`${host.alias}: HostName resolved to ${facts.hostname}, expected ${host.hostname}`);
			}
			if (host.user !== undefined && facts.user !== undefined && facts.user !== host.user) {
				errors.push(`${host.alias}: User resolved to ${facts.user}, expected ${host.user}`);
			}
			if (host.port !== undefined && facts.port !== undefined && facts.port !== host.port) {
				errors.push(`${host.alias}: Port resolved to ${facts.port}, expected ${host.port}`);
			}
		} catch (error) {
			errors.push(`${host.alias}: ${error instanceof Error ? error.message : String(error)}`);
		}
	}
	return errors;
}

/** Ensure the generated fragment exists and is only readable by the user. */
export async function ensurePrivateFile(file) {
	await mkdir(dirname(file), { recursive: true, mode: 0o700 });
	try {
		const info = await lstat(file);
		if ((info.mode & 0o077) !== 0) await chmod(file, 0o600);
	} catch {
		// Missing file is created by the next write.
	}
}

