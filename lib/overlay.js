/**
 * Per-host Loader overlay.
 *
 * The shared `dsh-remote` profile contains the official SSH packages but no
 * host. This overlay disables the local execution providers, points the
 * sandbox at the remote workspace, and inserts the four official SSH rows for
 * exactly one host. It also replaces the desktop directory-picker with the
 * copied remote browse backend, and mounts the copied one-shot Session
 * deeplink package, when the controller passes their absolute profile paths.
 * It is written fresh for every open and never contains credentials.
 * @module @junjiangao/dsh-plugin-remote-ssh/overlay
 */
import { chmod, mkdir, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/** Quote one YAML scalar with single quotes. */
export function yamlString(value) {
	const text = String(value);
	if (/[\u0000-\u001f\u007f]/.test(text)) throw new Error('overlay values must not contain control characters');
	return `'${text.replace(/'/g, "''")}'`;
}

/** Render the complete overlay text for one host. */
export function renderOverlay(input) {
	const {
		host,
		workspace,
		nodePath,
		helperPath,
		helperHash,
		permissionMode,
		referencePluginPath,
		directoryPickerPluginPath,
		deeplinkEntryPath,
		mirrorWorkspace,
	} = input;
	if (!/^[0-9a-f]{64}$/.test(helperHash)) throw new Error('helperHash must be a lowercase sha256 hex digest');
	if (!workspace.startsWith('/')) throw new Error('workspace must be an absolute remote path');
	if (!nodePath.startsWith('/')) throw new Error('nodePath must be an absolute remote path');
	if (!helperPath.startsWith('/')) throw new Error('helperPath must be an absolute remote path');
	if (referencePluginPath !== undefined && !referencePluginPath.startsWith('/')) {
		throw new Error('referencePluginPath must be an absolute local path');
	}
	if (directoryPickerPluginPath !== undefined && !directoryPickerPluginPath.startsWith('/')) {
		throw new Error('directoryPickerPluginPath must be an absolute local path');
	}
	if (deeplinkEntryPath !== undefined && !deeplinkEntryPath.startsWith('/')) {
		throw new Error('deeplinkEntryPath must be an absolute local path');
	}
	const lines = [
		'# Generated by @junjiangao/dsh-plugin-remote-ssh.',
		`# Host: ${host.alias} (${host.id})`,
		'# This file is rewritten for every open; edit hosts in the Web panel instead.',
		'',
		'# The official SSH rows replace the local execution world.',
		'- id: subprocess',
		'  disabled: true',
		'',
		'- id: sandbox',
		'  disabled: true',
		'',
		'- id: fs-sandbox',
		'  disabled: true',
		'',
		'# The node-script helper has no executable bootstrap, so PTC cannot run remotely.',
		'- id: ptc-runtime',
		'  disabled: true',
		'',
		'- id: workflow-ptc',
		'  disabled: true',
		'',
		'# Never hand a remote path to a local desktop application.',
		'- id: open-in-app',
		'  disabled: true',
		'',
		'- id: ui-open-in-app',
		'  disabled: true',
		'',
		...(directoryPickerPluginPath === undefined
			? []
			: [
					'# The shipped auto row resolves the local desktop chooser (a native folder',
					'# dialog on this machine). A remote window must browse the SSH host, so the',
					'# auto row is replaced by the remote backend inserted below plus the',
					'# official browse client surface it also used to mount.',
					'- id: directory-picker',
					'  disabled: true',
					'',
				]),
		...(referencePluginPath === undefined
			? []
			: [
					'# The shipped local @file scanner uses node:fs; replace it with one that',
					'# follows the official SSH filesystem mounted in this composition.',
					'- id: file-reference-local',
					'  disabled: true',
					'',
				]),
		'# workspaceRoot must be the remote workspace: the base row defaults to the',
		'# local process cwd, which would deny every remote write.',
		'- id: sandbox-policy',
		'  config:',
		`    mode: ${yamlString(permissionMode)}`,
		`    workspaceRoot: ${yamlString(workspace)}`,
		'',
		'# A desktop search provider plugin is absent from the remote profile; let the',
		'# web seam auto-select an installed provider instead of pinning a missing id.',
		'- id: web',
		'  config:',
		'    searchProvider: !!js undefined',
		'    fetchProvider: http',
		'',
		'- insert:',
		'    - id: ssh',
		"      name: '@deepseek-ai/dsh-ssh'",
		'      config:',
		`        host: ${yamlString(host.alias)}`,
		'        launch:',
		'          kind: node-script',
		`          node: ${yamlString(nodePath)}`,
		`        helper: ${yamlString(helperPath)}`,
		`        helperHash: ${yamlString(helperHash)}`,
		`        workspace: ${yamlString(workspace)}`,
		'',
		'    - id: fs-ssh',
		"      name: '@deepseek-ai/dsh-fs-ssh'",
		'',
		'    - id: subprocess-ssh',
		"      name: '@deepseek-ai/dsh-subprocess-ssh'",
		'',
		'    - id: sandbox-ssh',
		"      name: '@deepseek-ai/dsh-sandbox-ssh'",
		'',
		...(referencePluginPath === undefined
			? []
			: [
					'    # Remote @file completion follows dsh-fs-ssh instead of the host filesystem.',
					'    - id: remote-file-reference',
					`      name: ${yamlString(referencePluginPath)}`,
					'',
				]),
		...(directoryPickerPluginPath === undefined
			? []
			: [
					'    # Browse the SSH host through its own filesystem/subprocess providers;',
					'    # the disabled auto row above would have opened a local OS dialog.',
					'    - id: remote-directory-picker',
					`      name: ${yamlString(directoryPickerPluginPath)}`,
					'      config:',
					`        mirrorWorkspace: ${mirrorWorkspace === true ? 'true' : 'false'}`,
					`        workspace: ${yamlString(workspace)}`,
					'',
					'    - id: ui-directory-picker-browse',
					"      name: '@deepseek-ai/dsh-client-ui-directory-picker-browse'",
					'',
				]),
		...(deeplinkEntryPath === undefined
			? []
			: [
					'    # Claim the one-shot Session marker the main window wrote into this',
					'    # instance home before boot, then reveal that Session after the UI baseline.',
					'    - id: remote-session-deeplink',
					`      name: ${yamlString(deeplinkEntryPath)}`,
					'',
				]),
	];
	return lines.join('\n');
}

/** Atomically write the overlay for one host. */
export async function writeOverlay(instancesDir, hostId, content) {
	await mkdir(instancesDir, { recursive: true, mode: 0o700 });
	const file = join(instancesDir, `${hostId}.yml`);
	const temporary = `${file}.tmp-${process.pid}-${Date.now()}`;
	await writeFile(temporary, content, { encoding: 'utf8', mode: 0o600 });
	await chmod(temporary, 0o600).catch(() => undefined);
	await rename(temporary, file);
	return file;
}

/** Path of the overlay for one host. */
export function overlayPath(instancesDir, hostId) {
	return join(instancesDir, `${hostId}.yml`);
}
